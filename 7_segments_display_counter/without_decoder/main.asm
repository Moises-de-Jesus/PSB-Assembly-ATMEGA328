.nolist
.include "m328Pdef.inc"
.list

.equ BOTAO1 = PD5
.equ BOTAO2 = PD7
.def AUX = R16
.def FLAG = R18
.def COUNT = R17
.ORG 0x000
Inicializacoes:
	LDI COUNT,0b00000000
	LDI AUX,0b11111111
	OUT DDRD,AUX
	OUT DDRB,AUX
	OUT PORTD,AUX
	LDI AUX,0x00
	OUT PORTB,AUX
	NOP 
Principal:
	LDI COUNT,0b11111111
	OUT PORTB, COUNT
	RCALL Apertar0
	RJMP Principal
Apertar1:
	SBIC PIND,BOTAO1
	RET
	Esp_Soltar1:
		SBIS PIND,BOTAO1 
		RJMP Esp_Soltar1
	LDI FLAG, 0b00000000
	RCALL Atraso
	RET
